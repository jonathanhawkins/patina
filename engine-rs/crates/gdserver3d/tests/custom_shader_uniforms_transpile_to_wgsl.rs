//! pat-s3rrv.122 (step 1): the WGSL transpiler emits custom uniforms and `TIME`
//! instead of refusing them.
//!
//! `float_expr_to_wgsl` / `color_expr_to_wgsl` returned `None` for
//! `FloatExpr3D::Uniform`, `ColorExpr3D::Uniform` and `FloatExpr3D::BuiltinTime`,
//! so `custom_spatial_module_wgsl` produced no module and every uniform-driven
//! spatial shader collapsed to flat material albedo on the wgpu path.
//!
//! ⚠️ SCOPE — READ BEFORE ASSUMING THIS SHIPS PIXELS. This is the transpiler
//! half only. `custom_spatial_module_wgsl` still returns `None` for any body
//! that references `custom.`, on purpose: the pipeline declares three bind
//! groups (camera/model/light) and a module reading a group-3 block the layout
//! does not declare would fail pipeline creation — strictly worse than today's
//! flat-albedo fallback, which is wrong but renders. Removing that guard is
//! step 2 and must land WITH the group-3 layout, buffer upload and per-draw
//! binding. These tests pin the emitted text so step 2 only has to bind it.

use gdserver3d::shader::{
    fragment_body_to_wgsl_statements, wgsl_uniform_field, ColorExpr3D, FloatExpr3D,
    FragmentInstruction3D, UvAxis3D,
};

fn stmts(body: &[FragmentInstruction3D]) -> Vec<String> {
    fragment_body_to_wgsl_statements(body).expect("the body must transpile")
}

/// A `vec4` uniform reads the block field by name.
#[test]
fn a_color_uniform_reads_the_custom_block() {
    let body = [FragmentInstruction3D::SetColor(ColorExpr3D::Uniform(
        "tint".to_string(),
    ))];
    let out = stmts(&body).join("\n");
    assert!(
        out.contains("custom.tint"),
        "a `uniform vec4 tint` must read `custom.tint`, got: {out}"
    );
}

/// A scalar uniform takes `.x` — every field is a `vec4<f32>` so the emitted
/// struct needs no alignment padding.
#[test]
fn a_scalar_uniform_takes_the_x_component() {
    let body = [FragmentInstruction3D::SetColorAlpha(FloatExpr3D::Uniform(
        "alpha".to_string(),
    ))];
    let out = stmts(&body).join("\n");
    assert!(
        out.contains("custom.alpha.x"),
        "a scalar uniform must read `.x` off its vec4 slot, got: {out}"
    );
}

/// `TIME` is a field of the same block, not a separate binding.
#[test]
fn builtin_time_reads_the_custom_block() {
    let body = [FragmentInstruction3D::SetColorAlpha(
        FloatExpr3D::BuiltinTime,
    )];
    let out = stmts(&body).join("\n");
    assert!(
        out.contains("custom.time.x"),
        "TIME must read `custom.time.x`, got: {out}"
    );
}

/// CONTROL: a body with no uniforms must be unchanged by this bead.
///
/// Without this, an emitter that wrote `custom.` into every statement would
/// satisfy the assertions above and silently divert every existing shader —
/// including the UV-only ones that render correctly today — into the guarded
/// path, turning working output into flat albedo.
#[test]
fn a_uniform_free_body_does_not_touch_the_custom_block() {
    let body = [FragmentInstruction3D::SetColor(ColorExpr3D::Vec3(
        FloatExpr3D::UvComponent(UvAxis3D::X),
        FloatExpr3D::Literal(0.0),
        FloatExpr3D::Literal(0.0),
    ))];
    let out = stmts(&body).join("\n");
    assert!(
        !out.contains("custom."),
        "a body with no uniforms must not reference the uniform block: {out}"
    );
    assert!(
        out.contains("in.uv.x"),
        "the UV read must still transpile: {out}"
    );
}

/// The field name is generated by ONE function, so the reference and the
/// emitted struct declaration cannot drift apart.
#[test]
fn uniform_field_names_are_valid_wgsl_identifiers() {
    assert_eq!(wgsl_uniform_field("tint"), "tint");
    assert_eq!(wgsl_uniform_field("my_tint2"), "my_tint2");
    // A leading digit is not a legal WGSL identifier start.
    assert_eq!(wgsl_uniform_field("2tint"), "_2tint");
    // Anything else becomes an underscore rather than corrupting the module.
    assert_eq!(wgsl_uniform_field("a-b"), "a_b");
    assert_eq!(wgsl_uniform_field(""), "_");
}

/// `texture(sampler, uv)` emits a WGSL sampler read (pat-s3rrv.122).
///
/// ⚠️ The GPU path still FALLS BACK for these: `custom_layout` has no
/// texture/sampler pair yet, and a module reading bindings the layout lacks
/// fails pipeline creation — worse than the flat-albedo fallback. This pins the
/// emitted text so the binding work only has to declare it. The SOFTWARE path
/// samples these correctly already, which is what gives that work a baseline.
#[test]
fn a_texture_read_emits_a_sampler_pair() {
    let body = [FragmentInstruction3D::SetColor(ColorExpr3D::Texture(
        "tex".to_string(),
        Box::new(FloatExpr3D::UvComponent(UvAxis3D::X)),
        Box::new(FloatExpr3D::UvComponent(UvAxis3D::Y)),
    ))];
    let out = stmts(&body).join("\n");

    assert!(
        out.contains("textureSample(t_tex, s_tex,"),
        "a `texture(tex, UV)` must read the group-3 sampler pair, got: {out}"
    );
    // The UV expressions must still transpile through — a sampler read that
    // hard-coded its coordinates would sample one texel for the whole surface.
    assert!(
        out.contains("in.uv.x") && out.contains("in.uv.y"),
        "the sampled coordinates must come from the interpolated UV: {out}"
    );
}

/// The sampler pair and the uniform block share ONE name generator, so a
/// `sampler2D` and a buffer uniform can never collide on a field name.
#[test]
fn sampler_names_come_from_the_same_generator_as_uniform_fields() {
    let body = [FragmentInstruction3D::SetColor(ColorExpr3D::Texture(
        "2my-tex".to_string(),
        Box::new(FloatExpr3D::UvComponent(UvAxis3D::X)),
        Box::new(FloatExpr3D::UvComponent(UvAxis3D::Y)),
    ))];
    let out = stmts(&body).join("\n");
    let field = wgsl_uniform_field("2my-tex");

    assert_eq!(field, "_2my_tex");
    assert!(
        out.contains(&format!("t_{field}")) && out.contains(&format!("s_{field}")),
        "an awkward sampler name must be sanitised by the shared generator, not \
         emitted raw as invalid WGSL: {out}"
    );
}
